#!/bin/sh
# Generates the gitignored PlayTube config.php from the environment, then starts Apache.
set -e

APP_ROOT=/var/www/html
CONFIG="$APP_ROOT/config.php"

# Public URL the browser uses. In the Base44 sandbox the preview is served from
# https://3000-$BASE44_PUBLIC_HOST_SUFFIX, which the proxy forwards to this container.
if [ -n "${SITE_URL:-}" ]; then
    RESOLVED_SITE_URL="$SITE_URL"
elif [ -n "${PUBLIC_HOST_SUFFIX:-}" ]; then
    RESOLVED_SITE_URL="https://3000-$PUBLIC_HOST_SUFFIX"
else
    RESOLVED_SITE_URL="http://localhost:3000"
fi

if [ ! -f "$CONFIG" ]; then
    cat > "$CONFIG" <<PHP
<?php
// Generated by docker/base44/entrypoint.sh — playtube/config.php is gitignored.
// MySQL Hostname
\$sql_db_host = '${DB_HOST:-db}';
// MySQL Database User
\$sql_db_user = '${DB_USER:-playtube}';
// MySQL Database Password
\$sql_db_pass = '${DB_PASSWORD:-playtube}';
// MySQL Database Name
\$sql_db_name = '${DB_NAME:-playtube}';

// Site URL (the public preview URL)
\$site_url = '$RESOLVED_SITE_URL';

// Purchase code (the Envato installer is bypassed in this dev environment)
\$purchase_code = '';

// The preview proxy terminates TLS, so let the app serve whatever scheme it is reached on.
\$auto_redirect = false;
?>
PHP
fi

# The checkout is mounted with restrictive permissions; Apache (www-data) must be
# able to traverse the document root to read .htaccess and the application files.
chmod a+rx "$APP_ROOT"

# Runtime paths the application writes to.
mkdir -p "$APP_ROOT/upload/photos" "$APP_ROOT/upload/videos" "$APP_ROOT/assets/import"
chown -R www-data:www-data "$APP_ROOT/upload" "$APP_ROOT/assets/import"

exec "$@"
